CASE = {'nom': 0, 'gen': 1, 'acc': 2}


def num(n, case):
    """1..144 as words in the given case."""
    c = CASE[case]
    if n >= 100:
        return HUNDRED[c] + ('' if n == 100 else ' وَ' + num(n - 100, case))
    if n <= 10:
        return UNITS[n][c]
    if n == 12:
        return TWELVE[c]
    if n < 20:
        return TEENS[n]
    t, u = n - n % 10, n % 10
    tens = TENS[t][0 if c == 0 else 1]
    return tens if u == 0 else num(u, case) + ' وَ' + tens


def times_fact(a, b):
    return f'{num(a, "nom")} فِي {num(b, "gen")} يُسَاوِي {num(a * b, "acc")}.'


def division_fact(d, q):
    return f'{num(d * q, "nom")} عَلَى {num(d, "gen")} يُسَاوِي {num(q, "acc")}.'


