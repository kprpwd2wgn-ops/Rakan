HARAKAT = re.compile('[ً-ْٰ]')
LETTER = re.compile('[ء-ي]')


def write(name, lines):
    ids = [i for i, _ in lines]
    assert len(ids) == len(set(ids)), f'{name}: duplicate ids'
    for i, text in lines:
        bare = [w for w in re.findall('[؀-ۿ]+', text) if LETTER.search(w) and not HARAKAT.search(w)]
        assert not bare, f'{name} {i}: no tashkeel on {bare}'
    spec = {'voice': 'ar-SA-HamedNeural', 'lines': [{'id': i, 'text': t} for i, t in lines]}
    path = ROOT / name
    path.write_text(json.dumps(spec, ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
    print(f'wrote {path.name}: {len(lines)} lines, {sum(len(t) for _, t in lines)} characters')


